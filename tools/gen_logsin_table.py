#!/usr/bin/env python3
"""Generate the DX7 log-sine quarter-wave table.

Formula (die-readout derived, Shirriff part 3):

    y(n) = -log2(sin((n + 0.5) / 1024 * pi/2))
    value(n) = int(y(n) * 1024 + 0.5002)      # 14-bit, Q10, negated log2

The +0.5002 bias is part of the hardware's values (affects exactly one
entry when compared against a clean +0.5 rounding; the generator reports
the differing entries).

Usage: gen_logsin_table.py [--check FILE] [--dump]
  --check FILE   compare each generated value against an external
                 extraction, one decimal value per line (1024 lines).
  --dump         print the generated values, one per line (stdout).
Emits C (stdout) unless --dump; the external check report goes to stderr.
"""

import math
import sys

N = 1024
Q = 1024  # Q10 units
BIAS = 0.5002


def quarter_value(n):
    y = -math.log2(math.sin((n + 0.5) / N * math.pi / 2))
    return math.floor(y * Q + BIAS)  # int() truncation == floor for positive


def clean_value(n):
    y = -math.log2(math.sin((n + 0.5) / N * math.pi / 2))
    return math.floor(y * Q + 0.5)


def main():
    args = sys.argv[1:]
    dump = "--dump" in args
    check = None
    if "--check" in args:
        check = args[args.index("--check") + 1]

    values = [quarter_value(n) for n in range(N)]

    if dump:
        for v in values:
            print(v)
        return

    # Report the bias-quirk entries on stderr.
    quirks = [(n, values[n], clean_value(n)) for n in range(N)
              if values[n] != clean_value(n)]
    for n, v, c in quirks:
        print(f"bias-quirk: n={n} value={v} clean+0.5-rounding={c}",
              file=sys.stderr)
    print(f"bias-quirk entries: {len(quirks)}", file=sys.stderr)

    # Basic properties (also on stderr; stdout stays clean for redirection).
    # The quarter-wave log-sine is monotonically DECREASING from the
    # steep asymptote (silence) at n=0 down to 0 at n=1023.
    ok = True
    for n in range(N - 1):
        if values[n] < values[n + 1]:
            print(f"NOT monotonic nonincreasing at n={n}", file=sys.stderr)
            ok = False
    for n, v in enumerate(values):
        if v < 0 or v > 16383:
            print(f"value out of 14-bit range at n={n}: {v}", file=sys.stderr)
            ok = False
    print(f"monotonic (nonincreasing): {ok}", file=sys.stderr)
    print(f"range: [{values[0]}, {values[N - 1]}]  (steep start -> 0)", file=sys.stderr)
    print(f"value at n={N - 1}: {values[N - 1]}"
          f" (half-step offset keeps log(0) out of the table)", file=sys.stderr)

    if check:
        ext = [int(line) for line in open(check) if line.strip()]
        if len(ext) != N:
            print(f"extraction has {len(ext)} entries, expected {N}",
                  file=sys.stderr)
        mism = [(n, values[n], ext[n]) for n in range(N)
                if n < len(ext) and values[n] != ext[n]]
        for n, v, e in mism[:32]:
            print(f"mismatch: n={n} generated={v} extraction={e}",
                  file=sys.stderr)
        print(f"extraction mismatches: {len(mism)} / {len(ext)}",
              file=sys.stderr)

    # Emit C on stdout.
    print("/* Generated by tools/gen_logsin_table.py -- do not edit.")
    print(" * DX7 log-sine quarter-wave table (1024 x 14-bit, Q10, negated log2).")
    print(" * value(n) = int(-log2(sin((n+0.5)/1024*pi/2)) * 1024 + 0.5002)")
    print(" * Phase mapping: 12-bit phase = [S][M][q9..q0];")
    print(" *   q = low 10 bits as-is for the first quarter of a peak;")
    print(" *   q = complement (1023 - q) for the second quarter;")
    print(" *   S = wave half, output inverted for the negative half.")
    print(" */")
    print("#include <stdint.h>")
    print("const int16_t slopsix_logsin_quarter[1024] = {")
    for i in range(0, N, 12):
        row = ", ".join(str(v) for v in values[i:i + 12])
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
