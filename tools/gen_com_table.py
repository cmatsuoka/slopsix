#!/usr/bin/env python3
"""Generate the DX7 carrier-count compensation (COM) table.

Die readout (research A-05, dx7 section 2.4): every carrier of an
algorithm carries a COM value equal to the algorithm's carrier count
minus one, and the hardware subtracts log2(carrier_count) from the
carrier's log amplitude inside the algorithm box.

The COM ROM holds a 6-bit log value with two integer bits and four
fractional bits (the fraction counts sixteenths of a doubling). The die
analysis prints the patterns with three fraction digits, the fourth
fraction bit being zero:

    carrier count 1 -> 00.000   = 000000b =  0  (x1, no scaling)
    carrier count 2 -> 01.000   = 010000b = 16  (x1/2)
    carrier count 3 -> 01.101   = 011010b = 26  (x1/3, approximated)
    carrier count 4 -> 10.000   = 100000b = 32  (x1/4)
    carrier count 5 -> 10.011   = 100011b = 35  (x1/5, approximated)
    carrier count 6 -> 10.101   = 101010b = 42  (x1/6, approximated)

The three approximated patterns are the hardware's own 6-bit
approximations of log2(3), log2(5) and log2(6); they are reproduced
verbatim rather than recomputed.

The engine applies the value in the 12-bit Q8 log2 amplitude domain,
where one unit is 1/256 of a doubling, so the ROM's sixteenths become
sixteenths * 16 = the 8-bit-wide scale used by the amplitude pipeline.

Usage: gen_com_table.py [--check FILE] [--dump]
  --check FILE   compare each generated value against an external
                 extraction, one value per line (6 lines).
  --dump         print the generated values, one per line (stdout).
Emits C (stdout) unless --dump; the external check report goes to stderr.
"""

import sys

N = 6

# The six 6-bit ROM patterns, read from the die, with their meaning.
PATTERNS = [
    (0b000000, 1, False),   # 00.000 = log2(1)
    (0b010000, 2, False),   # 01.000 = log2(2)
    (0b011010, 3, True),    # 01.101 ~ log2(3)
    (0b100000, 4, False),   # 10.000 = log2(4)
    (0b100011, 5, True),    # 10.011 ~ log2(5)
    (0b101010, 6, True),    # 10.101 ~ log2(6)
]


def main():
    args = sys.argv[1:]
    dump = "--dump" in args
    check = None
    if "--check" in args:
        check = args[args.index("--check") + 1]

    values = [p for p, _count, _approx in PATTERNS]

    if dump:
        for v in values:
            print(v)
        return

    # Properties (stderr; stdout stays clean for redirection).
    ok = True
    for value, _pattern, count, approx in [(v, p, c, a)
                                           for v, (p, c, a) in zip(values, PATTERNS)]:
        bits = f"{value:06b}"
        int_part = int(bits[:2], 2)
        frac = int(bits[2:], 2)
        if value >> 4 != int_part or value & 0xF != frac:
            print(f"pattern split failed for {bits}", file=sys.stderr)
            ok = False
        print(f"carriers={count} pattern={bits} value={value} "
              f"({'approximated' if approx else 'exact'})",
              file=sys.stderr)
    for i in range(N - 1):
        if values[i] >= values[i + 1]:
            print(f"NOT increasing at index {i}", file=sys.stderr)
            ok = False
    print(f"monotonic increasing: {ok}", file=sys.stderr)
    print(f"range: [{values[0]}, {values[-1]}]", file=sys.stderr)
    print("scale: one unit = 1/16 of a doubling; the amplitude pipeline "
          "uses 1/256, so the value is multiplied by 16", file=sys.stderr)

    if check:
        ext = [int(line) for line in open(check) if line.strip()]
        if len(ext) != N:
            print(f"extraction has {len(ext)} entries, expected {N}",
                  file=sys.stderr)
        mism = [(i, values[i], ext[i]) for i in range(N)
                if i < len(ext) and values[i] != ext[i]]
        for i, v, e in mism[:32]:
            print(f"mismatch: i={i} generated={v} extraction={e}",
                  file=sys.stderr)
        print(f"extraction mismatches: {len(mism)} / {len(ext)}",
              file=sys.stderr)

    # Emit C on stdout.
    print("/* Generated by tools/gen_com_table.py -- do not edit.")
    print(" * DX7 carrier-count compensation (COM) table: 6 entries of the")
    print(" * hardware's 6-bit log ROM (2 integer bits, 4 fraction bits).")
    print(" * Index = carrier count - 1; the hardware subtracts log2(count)")
    print(" * from each carrier's log amplitude.")
    print(" * The three approximated patterns are the hardware's own.")
    print(" */")
    print("#include <stdint.h>")
    print("const uint8_t slopsix_com_log[6] = {")
    print("    /* 1 carrier */ " + str(values[0]) + ",")
    print("    /* 2 carriers */ " + str(values[1]) + ",")
    print("    /* 3 carriers */ " + str(values[2]) + ",")
    print("    /* 4 carriers */ " + str(values[3]) + ",")
    print("    /* 5 carriers */ " + str(values[4]) + ",")
    print("    /* 6 carriers */ " + str(values[5]))
    print("};")


if __name__ == "__main__":
    main()
