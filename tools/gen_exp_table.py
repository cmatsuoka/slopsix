#!/usr/bin/env python3
"""Generate the DX7 exponential table.

Formula (die-readout derived, Shirriff part 2):

    exp_table[k] = round(2^(k/1024) * 2048)     # 12-bit, Q11

The 12-bit value carries only the fractional part of a 14-bit log2 word
(4-bit integer octaves + 10-bit fraction); an implicit leading 1 is
appended. Final linear values:

    frequency path: exp_table[f] << (int >> 5)   -> 22 bits
    signal path:    exp_table[s] << int >> 13    -> 14 bits

Rounding convention: half-up (floor(x + 0.5)), pinned in the plan page.

Usage: gen_exp_table.py [--check FILE] [--dump]
  --check FILE   compare each generated value against an external
                 extraction, one decimal value per line (1024 lines).
  --dump         print the generated values, one per line (stdout).
Emits C (stdout) unless --dump; the external check report goes to stderr.
"""

import math
import sys

N = 1024
SCALE = 2048  # Q11


def exp_value(k):
    return math.floor((2.0 ** (k / N)) * SCALE + 0.5)


def main():
    args = sys.argv[1:]
    dump = "--dump" in args
    check = None
    if "--check" in args:
        check = args[args.index("--check") + 1]

    values = [exp_value(k) for k in range(N)]

    if dump:
        for v in values:
            print(v)
        return

    msg = []
    ok = True
    for k in range(N - 1):
        if values[k] > values[k + 1]:
            print(f"NOT monotonic at k={k}", file=sys.stderr)
            ok = False
    diffs = [values[k + 1] - values[k] for k in range(N - 1)]
    print(f"monotonic: {ok}", file=sys.stderr)
    print(f"range: [{values[0]}, {values[N - 1]}]", file=sys.stderr)
    print(f"first value (frac=0): {values[0]}"
          f" (expect 2048 exact)", file=sys.stderr)
    print(f"max delta between entries: {max(diffs)}"
          f" (4-bit deltas => 15 or less expected)", file=sys.stderr)

    if check:
        ext = [int(line) for line in open(check) if line.strip()]
        if len(ext) != N:
            print(f"extraction has {len(ext)} entries, expected {N}",
                  file=sys.stderr)
        mism = [(k, values[k], ext[k]) for k in range(N)
                if k < len(ext) and values[k] != ext[k]]
        for k, v, e in mism[:32]:
            print(f"mismatch: k={k} generated={v} extraction={e}",
                  file=sys.stderr)
        print(f"extraction mismatches: {len(mism)} / {len(ext)}",
              file=sys.stderr)

    print("/* Generated by tools/gen_exp_table.py -- do not edit.")
    print(" * DX7 exponential table (1024 x 12-bit, Q11).")
    print(" * exp_table[k] = round(2^(k/1024) * 2048); 2^frac with an")
    print(" * implicit leading 1 appended.")
    print(" * Frequency path: value<<int >> 5 (22-bit).")
    print(" * Signal path:    value<<int >> 13 (14-bit).")
    print(" */")
    print("#include <stdint.h>")
    print("const uint16_t slopsix_exp_q11[1024] = {")
    for i in range(0, N, 12):
        row = ", ".join(str(v) for v in values[i:i + 12])
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
