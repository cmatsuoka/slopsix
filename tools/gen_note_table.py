#!/usr/bin/env python3
"""Generate the DX7 note-to-log-frequency table.

Firmware closed form (research P-01, verified entry-for-entry against the
ROM's own 128-byte key-code table):

    T[n] = 0                                for n = 0
    T[n] = (n - 1) + floor((n - 1) / 3)     for n >= 1

The table stores the coarse key-code byte only; the fine term comes from
the key code's two low bits, exactly as the firmware does it:

    EGS field (1024 per octave)  = 64 * T + 21 * (T & 3)
    engine word (4096 per octave) = 256 * T + 84 * (T & 3)   (the field << 2)

Both spellings are emitted: the engine works in the 4096-per-octave word
(plan D-12) and hands the chip the 1024-per-octave field (plan D-16).

Usage: gen_note_table.py [--check FILE] [--dump]
  --check FILE   compare each generated T value against an external
                 extraction, one value per line (128 lines).
  --dump         print the generated T values, one per line (stdout).
Emits C (stdout) unless --dump; the external check report goes to stderr.
"""

import sys

N = 128


def t_value(n):
    """The ROM's key-code byte for note n."""
    if n == 0:
        return 0
    return (n - 1) + (n - 1) // 3


def field_datum(t):
    """The EGS frequency field (1024 per octave) for a key code."""
    return 64 * t + 21 * (t & 3)


def word_datum(t):
    """The engine's log-frequency word (4096 per octave) for a key code."""
    return 256 * t + 84 * (t & 3)


def main():
    args = sys.argv[1:]
    dump = "--dump" in args
    check = None
    if "--check" in args:
        check = args[args.index("--check") + 1]

    values = [t_value(n) for n in range(N)]

    if dump:
        for v in values:
            print(v)
        return

    # Properties (stderr; stdout stays clean for redirection).
    ok = True
    if values[0] != 0:
        print(f"T[0] = {values[0]}, expected 0 (safe default)", file=sys.stderr)
        ok = False
    for n in range(1, N):
        step = values[n] - values[n - 1]
        # n = 1 repeats the key-code-0 default (T[0] = T[1] = 0).
        if n == 1:
            if step != 0:
                print(f"unexpected step at n=1: {step}", file=sys.stderr)
                ok = False
        elif step not in (1, 2):
            print(f"unexpected step at n={n}: {step}", file=sys.stderr)
            ok = False
    # Every octave is exactly 1024 field units across 12 notes.
    for base in range(1, N - 12):
        span = field_datum(values[base + 12]) - field_datum(values[base])
        if span != 1024:
            print(f"octave span at n={base} is {span}, expected 1024",
                  file=sys.stderr)
            ok = False
    # The key-code table is monotonic nondecreasing.
    for n in range(N - 1):
        if values[n] > values[n + 1]:
            print(f"NOT monotonic at n={n}", file=sys.stderr)
            ok = False
    print(f"monotonic and octave-exact: {ok}", file=sys.stderr)
    print(f"T[0]={values[0]} T[1]={values[1]} T[13]={values[13]} "
          f"T[127]={values[127]}", file=sys.stderr)
    print(f"field datum(13) = {field_datum(values[13])} (one octave = 1024)",
          file=sys.stderr)
    print(f"field datum(69) = {field_datum(values[69])} "
          f"(word {word_datum(values[69])})", file=sys.stderr)

    if check:
        ext = [int(line) for line in open(check) if line.strip()]
        if len(ext) != N:
            print(f"extraction has {len(ext)} entries, expected {N}",
                  file=sys.stderr)
        mism = [(n, values[n], ext[n]) for n in range(N)
                if n < len(ext) and values[n] != ext[n]]
        for n, v, e in mism[:32]:
            print(f"mismatch: n={n} generated={v} extraction={e}",
                  file=sys.stderr)
        print(f"extraction mismatches: {len(mism)} / {len(ext)}",
              file=sys.stderr)

    # Emit C on stdout.
    print("/* Generated by tools/gen_note_table.py -- do not edit.")
    print(" * DX7 note-to-log-frequency tables (128 entries).")
    print(" * T[n] = 0 for n = 0; (n-1) + floor((n-1)/3) for n >= 1.")
    print(" * The key-code table matches the ROM's own 128-byte table.")
    print(" * The word is 4096 units per octave (the firmware's own units);")
    print(" * the EGS field is that word >> 2 (1024 units per octave).")
    print(" */")
    print("#include <stdint.h>")
    print("const uint8_t slopsix_note_t[128] = {")
    for i in range(0, N, 16):
        row = ", ".join(str(v) for v in values[i:i + 16])
        print(f"    {row},")
    print("};")
    print("")
    print("/* Log-frequency word per note: 256 * T + 84 * (T & 3),")
    print(" * 4096 units per octave (the firmware's domain).")
    print(" */")
    print("const uint16_t slopsix_note_word[128] = {")
    for i in range(0, N, 8):
        row = ", ".join(str(word_datum(v)) for v in values[i:i + 8])
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
