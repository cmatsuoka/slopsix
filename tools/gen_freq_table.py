#!/usr/bin/env python3
"""Generate the per-operator frequency-composition tables.

The engine's frequency word is the firmware's own 16-bit word with 4096
units per octave (plan decision D-12).  The per-operator composition adds
three offsets to the note's word:

  * the coarse ratio, log2(coarse), where coarse 0 means the 0.5 ratio;
  * the fine ratio, log2(1 + 0.01 * fine), which raises the ratio by up
    to 100 percent (the firmware table has a 101st word, 0x1000, that a
    serialised fine value of 100 reads);
  * the detune term, which is computed at note-on time from the note's
    absolute pitch (see src/slopsix_pitch.c).

The coarse and fine offsets are the working model transcribed from an
emulator analysis (research P-02, P-04); they are hypothesis-grade and live
in the engine's constant block.  The model's constants are given
in its own "2^24 per octave" word; this generator converts them to the
engine's 4096-per-octave word.

    coarse: the model's coarse_mul[coarse] = log2(coarse) for coarse >= 1
            and -1 (ratio 0.5) for coarse 0; the engine's offset is
            that value times 4096, rounded.
    fine:   floor(24204406.323123 * log(1 + 0.01 * fine) + 0.5) in the
            model's word; the engine's offset is that value divided by
            4096.  The table has 101 entries (0..100); the firmware's
            fine lookup is not bounded to 99, and its 101st table word is
            0x1000, i.e. the 2.0 ratio.

Usage: gen_freq_table.py [--dump]
  --dump   print the generated values, one per line, on stdout.
Emits C on stdout otherwise (the property report goes to stderr).
"""

import math
import sys

COARSE_N = 32
FINE_N = 101

# The engine's word: 4096 units per octave.
UNITS_PER_OCTAVE = 4096

# The model's word: 2^24 units per octave.
MODEL_UNITS_PER_OCTAVE = 1 << 24

# The model's fine coefficient: floor(MODEL_FINE_COEF *
# log(1 + 0.01 * fine) + 0.5) in the model's word.
MODEL_FINE_COEF = 24204406.323123


def coarse_offset(coarse):
    """The engine's word offset for the coarse ratio, in 4096/octave."""
    if coarse == 0:
        # The hardware's coarse 0 is the half ratio: log2(0.5) = -1.
        return -UNITS_PER_OCTAVE
    return int(math.floor(MODEL_UNITS_PER_OCTAVE * math.log2(coarse)
                          / UNITS_PER_OCTAVE + 0.5))


def fine_offset(fine):
    """The engine's word offset for the fine ratio, in 4096/octave."""
    model = math.floor(MODEL_FINE_COEF * math.log(1 + 0.01 * fine) + 0.5)
    return model // UNITS_PER_OCTAVE


def main():
    args = sys.argv[1:]
    dump = "--dump" in args

    coarse = [coarse_offset(c) for c in range(COARSE_N)]
    fine = [fine_offset(f) for f in range(FINE_N)]

    if dump:
        for v in coarse + fine:
            print(v)
        return

    # Properties (stderr; stdout stays clean for redirection).
    ok = True
    if coarse[0] != -UNITS_PER_OCTAVE:
        print(f"coarse[0] is {coarse[0]}, expected {-UNITS_PER_OCTAVE}",
              file=sys.stderr)
        ok = False
    if coarse[1] != 0:
        print(f"coarse[1] is {coarse[1]}, expected 0 (ratio 1)", file=sys.stderr)
        ok = False
    if coarse[2] != UNITS_PER_OCTAVE:
        print(f"coarse[2] is {coarse[2]}, expected {UNITS_PER_OCTAVE} "
              "(ratio 2)", file=sys.stderr)
        ok = False
    if fine[0] != 0:
        print(f"fine[0] is {fine[0]}, expected 0", file=sys.stderr)
        ok = False
    for i in range(COARSE_N - 1):
        if coarse[i + 1] <= coarse[i]:
            print(f"coarse not increasing at {i}", file=sys.stderr)
            ok = False
    for i in range(FINE_N - 1):
        if fine[i + 1] <= fine[i]:
            print(f"fine not increasing at {i}", file=sys.stderr)
            ok = False
    print(f"monotonic: {ok}", file=sys.stderr)
    print(f"coarse range: [{coarse[0]}, {coarse[-1]}]", file=sys.stderr)
    print(f"fine range: [{fine[0]}, {fine[-1]}]", file=sys.stderr)

    print("/* Generated by tools/gen_freq_table.py -- do not edit.")
    print(" * Per-operator frequency-composition offsets, in the engine's")
    print(" * 4096-units-per-octave frequency word.")
    print(" * coarse[n] = log2(n) in 4096/octave units (coarse 0 = the 0.5")
    print(" * ratio, i.e. -1 octave); fine[n] = log2(1 + 0.01*n) for")
    print(" * n = 0..99, plus the firmware table's 101st word at n = 100")
    print(" * (log2(2.0), the value a serialised fine of 100 reads).")
    print(" * Evidence grade: emulator-derived model (research P-02, P-04).")
    print(" */")
    print("#include <stdint.h>")
    print("const int32_t slopsix_coarse_offset[32] = {")
    for i in range(0, COARSE_N, 8):
        row = ", ".join(str(v) for v in coarse[i:i + 8])
        print(f"    {row},")
    print("};")
    print("const int16_t slopsix_fine_offset[101] = {")
    for i in range(0, FINE_N, 10):
        row = ", ".join(str(v) for v in fine[i:i + 10])
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
